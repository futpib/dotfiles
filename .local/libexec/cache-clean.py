def read_generated(path, limit=-1):
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NOATIME)
    with os.fdopen(fd) as stream:
        return stream.read(limit)


def regular(path):
    return stat.S_ISREG(path.lstat().st_mode)


def cmake_source(build):
    cache = build / "CMakeCache.txt"
    if not regular(cache) or build != build.resolve() or (build / "CMakeLists.txt").exists():
        return None
    lines = read_generated(cache).splitlines()
    if lines[:1] != ["# This is the CMakeCache file."]:
        return None
    values = {}
    for key in ("CMAKE_CACHEFILE_DIR", "CMAKE_HOME_DIRECTORY", "CMAKE_GENERATOR"):
        matches = [line.split("=", 1)[1] for line in lines if line.startswith(key + ":INTERNAL=")]
        if len(matches) != 1:
            return None
        values[key] = matches[0]
    if values["CMAKE_CACHEFILE_DIR"] != str(build):
        return None
    source = Path(values["CMAKE_HOME_DIRECTORY"])
    if not source.is_absolute() or not regular(source / "CMakeLists.txt"):
        return None
    source = source.resolve()
    if source == build or build in source.parents:
        return None
    check = build / "CMakeFiles/cmake.check_cache"
    if not regular(check) or "generated by cmake" not in read_generated(check):
        return None
    generator = values["CMAKE_GENERATOR"]
    backend = build / ("Makefile" if generator == "Unix Makefiles" else "build.ninja")
    if generator not in ("Ninja", "Ninja Multi-Config", "Unix Makefiles") or not regular(backend):
        return None
    if not read_generated(backend, 100).startswith("# CMAKE generated file: DO NOT EDIT!\n"):
        return None
    return source


def incremental(path, target, cutoff, apply, only_session=None):
    profile = path.parent
    if path != path.resolve() or path.name != "incremental" or not path.is_relative_to(target):
        return "preserve-ambiguous", 0
    if len(profile.relative_to(target).parts) not in (1, 2):
        return "preserve-ambiguous", 0
    info = target / ".rustc_info.json"
    if not regular(info):
        return "preserve-ambiguous", 0
    data = json.loads(read_generated(info))
    if not isinstance(data, dict) or not isinstance(data.get("rustc_fingerprint"), int) or not isinstance(data.get("outputs"), dict):
        return "preserve-ambiguous", 0
    if not (profile / "deps").is_dir() or not (profile / ".fingerprint").is_dir():
        return "preserve-ambiguous", 0

    locks = []
    sessions = []
    entries = [path]
    seen_inodes = set()
    size = 0

    def lock(file):
        fd = os.open(file, os.O_RDWR | os.O_NOFOLLOW)
        locks.append(fd)
        if not stat.S_ISREG(os.fstat(fd).st_mode):
            raise ValueError("nonregular lock")
        fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)

    try:
        # Cargo serializes profile builds with this lock. Keep it held through
        # deletion, and also take rustc's individual incremental session locks.
        lock(profile / ".cargo-lock")
        crates = [only_session.parent] if only_session else list(path.iterdir())
        if only_session and (only_session.parent.parent != path or only_session != only_session.resolve()):
            return "preserve-ambiguous", 0
        for crate in crates:
            if crate.is_symlink() or not crate.is_dir() or not re.fullmatch(r"[\w-]+-[a-z0-9]+", crate.name):
                return "preserve-ambiguous", 0
            entries.append(crate)
            children = [only_session, only_session.parent / (only_session.name.rsplit("-", 1)[0] + ".lock")] if only_session else list(crate.iterdir())
            for entry in children:
                entries.append(entry)
                if regular(entry) and re.fullmatch(r"s-[a-z0-9]+-[a-z0-9]+\.lock", entry.name):
                    lock(entry)
                    continue
                match = re.fullmatch(r"(s-[a-z0-9]+-[a-z0-9]+)-[a-z0-9]+", entry.name)
                if entry.is_symlink() or not entry.is_dir() or not match:
                    return "preserve-ambiguous", 0
                if not regular(crate / (match[1] + ".lock")):
                    return "preserve-ambiguous", 0
                files = list(entry.iterdir())
                if not files or not (entry / "dep-graph.bin").is_file():
                    return "preserve-ambiguous", 0
                for file in files:
                    if not regular(file) or not re.fullmatch(r"(?:[a-z0-9]+\.o|dep-graph\.bin|query-cache\.bin|work-products\.bin|metadata\.rmeta)", file.name):
                        return "preserve-ambiguous", 0
                entries.extend(files)
                sessions.append(entry)
        if not sessions:
            return "preserve-empty", 0
        for entry in entries:
            if only_session and entry not in sessions and not any(session in entry.parents for session in sessions):
                continue
            st = entry.lstat()
            if st.st_dev != path.stat().st_dev:
                return "preserve-ambiguous", 0
            if cutoff and st.st_mtime > cutoff:
                return "preserve-fresh", 0
            inode = (st.st_dev, st.st_ino)
            if stat.S_ISREG(st.st_mode) and inode not in seen_inodes:
                seen_inodes.add(inode)
                size += st.st_blocks * 512
        if apply:
            # Leave lock files and their parent directories in place. A new
            # rustc invocation can create its own session without losing it.
            for session in sessions:
                shutil.rmtree(session)
        return "selected", size
    finally:
        for fd in locks:
            os.close(fd)


GIB = 1024 ** 3
WEEK = 7 * 86400
HOUR = 3600
AGES = (("7d", WEEK), ("3d", 3 * 86400), ("1d", 86400), ("6h", 6 * HOUR), ("1h", HOUR))


def below(path, root):
    return path == root or str(path).startswith(str(root).rstrip("/") + "/")


def human(size):
    return f"{size / GIB:.2f} GiB"


def log(message):
    print(f"cache-clean: {message}", flush=True)


def walk(path, device):
    st = path.lstat()
    if st.st_dev != device or st.st_uid != os.geteuid():
        raise ValueError(f"foreign filesystem or owner: {path}")
    yield path, st
    if stat.S_ISDIR(st.st_mode):
        fd = os.open(path, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_NOATIME)
        try:
            with os.scandir(fd) as entries:
                children = [path / entry.name for entry in entries]
            for child in children:
                if child.name == ".git":
                    raise ValueError(f"embedded source repository: {path}")
                yield from walk(child, device)
        finally:
            os.close(fd)


def directories(path):
    fd = os.open(path, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_NOATIME)
    try:
        with os.scandir(fd) as entries:
            return [path / entry.name for entry in entries if entry.is_dir(follow_symlinks=False)]
    finally:
        os.close(fd)


def maven_version(path):
    def entries(directory):
        fd = os.open(directory, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_NOATIME)
        try:
            with os.scandir(fd) as contents:
                return [directory / entry.name for entry in contents]
        finally:
            os.close(fd)
    hashes = entries(path)
    prefix = f"{path.parent.name}-{path.name}"
    if not hashes:
        return False
    for directory in hashes:
        # Gradle's SHA-1 directory keys omit leading zeroes.
        if directory.is_symlink() or not re.fullmatch(r"(?:[0-9a-f]{1,40}|[0-9a-f]{64})", directory.name):
            return False
        artifacts = entries(directory)
        if not artifacts or not all(regular(file) and file.name.startswith((prefix + ".", prefix + "-")) for file in artifacts):
            return False
    return True


@dataclass
class Usage:
    used: float
    reclaimable: int
    identity: tuple


@dataclass
class Candidate:
    kind: str
    path: Path
    project: Path
    target: Path | None = None
    usage: Usage | None = None
    locks: tuple = ()


class Processes:
    def __init__(self):
        self.paths = set()
        self.cwd = set()
        self.compilers = set()
        self.commands = set()
        for process in Path("/proc").iterdir():
            if not process.name.isdigit():
                continue
            try:
                if process.stat().st_uid != os.geteuid():
                    continue
                command = (process / "comm").read_text().strip()
                self.commands.add(command)
                cwd = Path(os.readlink(process / "cwd"))
                exe = Path(os.readlink(process / "exe"))
                self.cwd.add(cwd)
                paths = {exe}
                for arg in (process / "cmdline").read_bytes().split(b"\0"):
                    value = os.fsdecode(arg)
                    if not value:
                        continue
                    path = Path(value)
                    if path.is_absolute():
                        paths.add(path)
                    elif (cwd / path).exists():
                        paths.add((cwd / path).resolve())
                for folder in ("fd", "map_files"):
                    try:
                        for file in (process / folder).iterdir():
                            try:
                                value = os.readlink(file)
                                if value.startswith("/"):
                                    paths.add(Path(value))
                            except OSError:
                                pass
                    except OSError:
                        pass
                self.paths.update(paths)
                if command in ("cargo", "rustc", "clippy-driver"):
                    self.compilers.update(paths | {cwd})
            except OSError:
                continue

        # Index ancestors once rather than comparing every open path with every
        # candidate. Membership preserves the same component-boundary checks.
        self.active_trees = self.ancestors(self.paths | self.cwd)
        self.compiler_trees = self.ancestors(self.compilers)

    @staticmethod
    def ancestors(paths):
        return {parent for path in paths for parent in (path, *path.parents)}

    def busy(self, candidate):
        # A shared-cache blocker applies to every package. Check it before
        # searching individual open paths, including for packages we will skip.
        if candidate.kind == "tool" and self.commands.intersection((
            "cargo", "rustc", "clippy-driver", "java", "gradle", "dart",
            "flutter", "npm", "pnpm", "bun",
        )):
            return True
        if candidate.path in self.active_trees:
            return True
        if candidate.kind == "incremental":
            return candidate.project in self.compiler_trees
        if candidate.kind == "cache":
            return False
        if candidate.kind == "tool":
            return False
        return candidate.project in self.active_trees


class Cleaner:
    def __init__(self, args, free=None, processes=None):
        self.args = args
        self.home = Path.home().resolve()
        self.filesystem = Path(args.filesystem).resolve()
        self.device = self.filesystem.stat().st_dev
        space = os.statvfs(self.filesystem)
        self.capacity = space.f_blocks * space.f_frsize
        self.free = free or (lambda: self.available())
        self.snapshot = processes or Processes
        self.processes = None
        self.processes_refreshed = 0
        self.low = watermark(args.low_watermark, self.capacity)
        self.high = watermark(args.high_watermark, self.capacity)
        if not 0 < self.low < self.high < self.capacity:
            raise ValueError("watermarks must satisfy 0 < low < high < filesystem capacity")
        self.cache = Path(os.environ.get("XDG_CACHE_HOME", self.home / ".cache")).resolve()
        config = Path(os.environ.get("XDG_CONFIG_HOME", self.home / ".config"))
        self.protected = [
            self.cache / "opencode",
            self.cache / "ms-playwright", self.cache / "puppeteer",
            self.cache / "Cypress", self.cache / "selenium",
            Path(os.environ.get("OPENCODE_CONFIG_DIR", config / "opencode")).resolve(),
            self.home / ".codex/packages", self.home / ".local/libexec",
            self.home / ".local/share/pnpm/global", self.home / ".bun/install/global",
            *[Path(path).resolve() for path in args.protect],
        ]
        if (self.home / ".pub-cache/global_packages").is_dir():
            # Global Dart applications can load source from hosted packages.
            self.protected.append(self.home / ".pub-cache")
        self.removed = set()
        self.changed_directories = {}
        self.inventory = None
        self.virtual_free = None
        self.count = 0
        self.tracked_cache = {}
        self.git_scopes = {}
        self.now = time.time()
        self.retry_state = Path(os.environ.get("XDG_STATE_HOME", self.home / ".local/state")) / "cache-clean/pressure.json"

    def current_processes(self, force=False):
        if self.processes is None or force or time.monotonic() - self.processes_refreshed > 1:
            self.processes = self.snapshot()
            self.processes_refreshed = time.monotonic()
        return self.processes

    def retry_ready(self):
        if not self.args.retry_after or not self.args.apply:
            return True
        identity = [str(self.filesystem), self.low, self.high]
        now = time.time()
        try:
            state = json.loads(self.retry_state.read_text())
            elapsed = max(0, now - float(state["started"]))
            if state["identity"] == identity and elapsed < self.args.retry_after:
                log(f"previous cleanup attempt is cooling down; retry in {self.args.retry_after - elapsed:.0f}s")
                return False
        except (OSError, ValueError, TypeError, KeyError):
            pass
        self.retry_state.parent.mkdir(parents=True, exist_ok=True)
        # Record before discovery so timeouts and interrupted runs also back off.
        with tempfile.NamedTemporaryFile(mode="w", dir=self.retry_state.parent, delete=False) as stream:
            temporary = Path(stream.name)
            try:
                json.dump({"identity": identity, "started": now}, stream)
                stream.flush()
                temporary.replace(self.retry_state)
            finally:
                temporary.unlink(missing_ok=True)
        return True

    def clear_retry(self):
        if self.args.retry_after and self.args.apply:
            self.retry_state.unlink(missing_ok=True)

    def available(self):
        space = os.statvfs(self.filesystem)
        return space.f_bavail * space.f_frsize

    def space(self):
        return self.virtual_free if self.virtual_free is not None else self.free()

    def protected_path(self, path):
        return any(below(path, root) or below(root, path) for root in self.protected)

    def was_removed(self, path):
        if not self.removed:
            return False
        return path in self.removed or any(parent in self.removed for parent in path.parents)

    def usage(self, path):
        newest = 0
        size = 0
        inodes = set()
        identity = None
        for entry, st in walk(path, self.device):
            if self.was_removed(entry):
                continue
            if identity is None:
                identity = (st.st_dev, st.st_ino)
            modified = st.st_mtime
            override = self.changed_directories.get(entry)
            if override and override[0] == st.st_mtime_ns:
                modified = override[1]
            # Directory atime reflects enumeration, including find in discovery.
            # File atime/mtime records approximate use on relatime filesystems.
            newest = max(newest, modified if stat.S_ISDIR(st.st_mode) else max(modified, st.st_atime))
            inode = (st.st_dev, st.st_ino)
            if stat.S_ISREG(st.st_mode) and st.st_nlink == 1 and inode not in inodes:
                size += st.st_blocks * 512
                inodes.add(inode)
        return Usage(newest, size, identity)

    def tracked(self, path, scope):
        if scope not in self.git_scopes:
            result = subprocess.run(["git", "-C", str(scope), "rev-parse", "--show-toplevel"],
                                    capture_output=True, text=True)
            self.git_scopes[scope] = Path(result.stdout.strip()) if not result.returncode else None
        root = self.git_scopes[scope]
        if root is None:
            return False
        index_result = subprocess.run(["git", "-C", str(root), "rev-parse", "--git-path", "index"],
                                      check=True, capture_output=True, text=True)
        index = Path(index_result.stdout.strip())
        if not index.is_absolute():
            index = root / index
        stamp = index.stat().st_mtime_ns if index.exists() else None
        cached = self.tracked_cache.get(root)
        if cached is None or cached[0] != stamp:
            files = subprocess.run(["git", "-C", str(root), "ls-files", "-z"], check=True, capture_output=True).stdout
            cached = (stamp, {root / os.fsdecode(name) for name in files.split(b"\0") if name})
            self.tracked_cache[root] = cached
        return any(below(file, path) for file in cached[1])

    def load_inventory(self):
        if self.inventory is None:
            script = Path(__file__).resolve().parent.parent / "bin/cache-clean"
            command = [str(script), "--build-inventory"]
            for root in self.args.build_root:
                command += ["--build-root", root]
            fields = subprocess.run(command, check=True, capture_output=True).stdout.split(b"\0")
            if fields[-1] != b"" or (len(fields) - 1) % 4:
                raise ValueError("invalid build inventory")
            self.inventory = []
            for offset in range(0, len(fields) - 1, 4):
                kind, path, project, target = map(os.fsdecode, fields[offset:offset + 4])
                self.inventory.append(Candidate(kind, Path(path), Path(project), Path(target) if target else None))
        return self.inventory

    def cache_candidates(self):
        if not self.cache.is_dir() or self.cache == self.home or self.cache == Path("/"):
            return []
        candidates = []
        # Preserve runtime trees before entering them, and never follow symlinks.
        def visit(path):
            if self.protected_path(path):
                return
            try:
                st = path.lstat()
                if st.st_dev != self.device or st.st_uid != os.geteuid():
                    return
                if stat.S_ISDIR(st.st_mode):
                    if ((path / "pyvenv.cfg").is_file() or (path / "bin").is_dir() or
                        (path / "package.json").is_file() and (path / "node_modules").is_dir()):
                        return
                    fd = os.open(path, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_NOATIME)
                    try:
                        with os.scandir(fd) as entries:
                            children = [path / entry.name for entry in entries]
                        for child in children:
                            visit(child)
                    finally:
                        os.close(fd)
                elif stat.S_ISREG(st.st_mode) or stat.S_ISLNK(st.st_mode):
                    candidates.append(Candidate("cache", path, self.cache))
            except OSError:
                return
        # The cache root contains protected descendants, so visit its children.
        if self.cache.stat().st_dev == self.device:
            fd = os.open(self.cache, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_NOATIME)
            try:
                with os.scandir(fd) as entries:
                    children = [self.cache / entry.name for entry in entries]
                for child in children:
                    visit(child)
            finally:
                os.close(fd)
        return candidates

    def build_candidates(self, incremental_only):
        candidates = []
        for item in self.load_inventory():
            if incremental_only:
                if item.kind != "incremental":
                    continue
                try:
                    for crate in directories(item.path):
                        for session in directories(crate):
                            candidates.append(Candidate("incremental", session, item.project, item.target))
                except (OSError, ValueError):
                    continue
            elif item.kind == "rust":
                try:
                    if not self.valid_build(item):
                        continue
                    children = directories(item.path)
                    profiles = list(children)
                    for child in children:
                        try:
                            profiles.extend(directories(child))
                        except OSError:
                            continue
                    for profile in profiles:
                        candidate = Candidate("rust-profile", profile, item.project, item.path)
                        if self.valid_build(candidate):
                            candidates.append(candidate)
                except (OSError, ValueError):
                    continue
            elif item.kind not in ("incremental", "venv", "unknown"):
                candidates.append(item)
        return candidates

    def tool_candidates(self):
        paths = [".gradle/caches", ".gradle/wrapper/dists", ".cargo/registry/cache", ".cargo/registry/src",
                 ".cargo/git", ".npm/_cacache", ".pub-cache", ".bun/install/cache"]
        candidates = []
        for name in paths:
            root = self.home / name
            if not root.is_dir() or root.is_symlink():
                continue
            try:
                fd = os.open(root, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_NOATIME)
                try:
                    with os.scandir(fd) as entries:
                        children = [root / entry.name for entry in entries]
                    for child in children:
                        if child.is_symlink():
                            continue
                        if name in (".cargo/registry/cache", ".cargo/registry/src"):
                            if not child.is_dir():
                                continue
                            locks = tuple(self.home / ".cargo" / lock for lock in (".package-cache", ".package-cache-mutate"))
                            if not all(regular(lock) for lock in locks):
                                continue
                            fd_registry = os.open(child, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_NOATIME)
                            try:
                                with os.scandir(fd_registry) as packages:
                                    entries = [child / package.name for package in packages]
                            finally:
                                os.close(fd_registry)
                            for package in entries:
                                if name.endswith("/cache"):
                                    valid = package.suffix == ".crate" and regular(package)
                                else:
                                    valid = package.is_dir() and not package.is_symlink() and all(
                                        (package / marker).is_file() and not (package / marker).is_symlink()
                                        for marker in (".cargo-ok", "Cargo.toml"))
                                if valid:
                                    candidates.append(Candidate("tool", package, root, locks=locks))
                        elif name == ".gradle/caches" and child.name == "modules-2":
                            store = child / "files-2.1"
                            lock = child / "modules-2.lock"
                            if not store.is_dir() or store.is_symlink() or not regular(lock):
                                continue
                            for group in directories(store):
                                for module in directories(group):
                                    for version in directories(module):
                                        try:
                                            if maven_version(version):
                                                candidates.append(Candidate("tool", version, root, locks=(lock,)))
                                        except OSError:
                                            continue
                        elif child.is_dir():
                            candidates.append(Candidate("tool", child, root))
                finally:
                    os.close(fd)
            except OSError:
                continue
        return candidates

    def prepare(self, candidates, age):
        selected = []
        busy = 0
        processes = None
        for candidate in candidates:
            try:
                if self.protected_path(candidate.path):
                    continue
                # Selection never deletes anything, so one snapshot can reject
                # busy trees before metadata scans. Deletion rechecks eligibility.
                if processes is None:
                    processes = self.current_processes()
                if processes.busy(candidate):
                    busy += 1
                    continue
                if candidate.path.is_symlink() and candidate.kind != "cache":
                    continue
                if candidate.path.parent.resolve() != candidate.path.parent:
                    continue
                if (candidate.project / ".cache-clean-keep").exists() or (candidate.path / ".cache-clean-keep").exists():
                    continue
                if self.was_removed(candidate.path):
                    continue
                candidate.usage = self.usage(candidate.path)
                if candidate.usage.used <= self.now - age and candidate.usage.reclaimable:
                    selected.append(candidate)
            except (OSError, ValueError):
                continue
        if busy:
            log(f"preserve {busy} busy cache/build unit(s)")
        return sorted(selected, key=lambda item: (item.usage.used, str(item.path)))

    def valid_build(self, item):
        path = item.path
        if item.kind in ("cache", "tool"):
            return True
        if item.kind == "cmake":
            source = cmake_source(path)
            return source is not None and below(source, item.project)
        if item.kind == "incremental":
            return incremental(path.parent.parent, item.target, 0, False, path)[0] == "selected"
        if item.kind in ("rust", "rust-profile"):
            target = item.target if item.kind == "rust-profile" else path
            if item.kind == "rust-profile":
                if target is None or not below(path, target) or len(path.relative_to(target).parts) not in (1, 2):
                    return False
                lock = path / ".cargo-lock"
                if not lock.is_file() or lock.is_symlink() or not all((path / name).is_dir() and not (path / name).is_symlink() for name in ("deps", ".fingerprint")):
                    return False
            data = json.loads(read_generated(target / ".rustc_info.json"))
            return isinstance(data, dict) and isinstance(data.get("outputs"), dict) and isinstance(data.get("rustc_fingerprint"), int)
        if item.kind == "node":
            return (path.parent / "package.json").is_file() and any((path.parent / name).is_file() for name in (
                "package-lock.json", "pnpm-lock.yaml", "yarn.lock", "bun.lock", "bun.lockb"))
        if item.kind in ("flutter", "dart"):
            return (path.parent / "pubspec.yaml").is_file()
        if item.kind == "gradle":
            return any((path.parent / name).is_file() for name in (
                "gradlew", "settings.gradle", "settings.gradle.kts", "build.gradle", "build.gradle.kts"))
        if item.kind == "meson":
            return (path / "meson-private/coredata.dat").is_file() and (path / "build.ninja").is_file()
        return False

    def remember_parents(self, path):
        parents = {}
        for parent in path.parents:
            if parent == self.home or not below(parent, self.home):
                break
            try:
                st = parent.stat()
                old = self.changed_directories.get(parent)
                parents[parent] = old[1] if old and old[0] == st.st_mtime_ns else st.st_mtime
            except OSError:
                pass
        return parents

    def remove(self, item, apply=True):
        if item.kind == "cache":
            if apply:
                item.path.unlink()
        elif item.kind == "incremental":
            result, _ = incremental(item.path.parent.parent, item.target, 0, apply, item.path)
            if result != "selected":
                raise ValueError(result)
        else:
            # Keep lock inodes and names stable so a waiting builder cannot
            # acquire a newly created replacement while deletion is underway.
            with ExitStack() as stack:
                keep = set(item.locks)
                for path, st in walk(item.path, self.device):
                    if stat.S_ISREG(st.st_mode) and (path.name.endswith(".lock") or path.name == ".cargo-lock"):
                        keep.add(path)
                for path in sorted(keep):
                    fd = os.open(path, os.O_RDWR | os.O_NOFOLLOW)
                    stack.callback(os.close, fd)
                    if not stat.S_ISREG(os.fstat(fd).st_mode):
                        raise ValueError("nonregular cache lock")
                    fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
                    fcntl.lockf(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
                if any(lock.name == "modules-2.lock" for lock in item.locks) and not maven_version(item.path):
                    raise ValueError("unrecognized Maven artifact version")
                if apply:
                    remove_preserving_locks(item.path, keep)

    def consume(self, candidates, age):
        for item in self.prepare(candidates, age):
            if self.space() >= self.high:
                return True
            try:
                # A long scan or previous removal may have changed eligibility.
                if self.was_removed(item.path):
                    continue
                current = self.usage(item.path)
                if current.identity != item.usage.identity or current.used > item.usage.used:
                    log(f"preserve changed {item.path}")
                    continue
                processes = self.current_processes(force=item.kind not in ("cache", "incremental"))
                scope = item.project if item.kind in ("cache", "tool") else item.path.parent
                if processes.busy(item) or self.tracked(item.path, scope) or not self.valid_build(item):
                    log(f"preserve protected/busy/unrecognized {item.path}")
                    continue
                parents = self.remember_parents(item.path)
                self.remove(item, self.args.apply)
                if self.args.apply:
                    for parent, old_time in parents.items():
                        if parent.exists():
                            self.changed_directories[parent] = (parent.stat().st_mtime_ns, old_time)
                else:
                    self.virtual_free += current.reclaimable
                self.removed.add(item.path)
                self.count += 1
                verb = "removed" if self.args.apply else "would remove"
                used = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(item.usage.used))
                if item.kind != "cache" or self.count <= 10 or self.count % 1000 == 0:
                    log(f"{verb} {item.kind} {item.path}; last use {used}; available {human(self.space())}")
            except (OSError, ValueError, subprocess.SubprocessError) as error:
                log(f"preserve {item.path}: {error}")
        return self.space() >= self.high

    def docker_cache(self, age):
        if self.args.no_docker or not shutil.which("docker"):
            return
        def output(arguments):
            return subprocess.run(["docker", *arguments], check=True, capture_output=True, text=True, timeout=15).stdout
        def query(arguments):
            return json.loads(output(arguments))
        try:
            endpoint = query(["context", "inspect", "--format", "{{json .Endpoints.docker.Host}}"])
            if not endpoint.startswith("unix://"):
                return
            info = query(["info", "--format", "{{json .}}"])
            if Path(info["DockerRootDir"]).stat().st_dev != self.device:
                return
            builders = [json.loads(line) for line in output(["buildx", "ls", "--format", "{{json .}}"]).splitlines()]
            selected = {json.dumps(builder, sort_keys=True): builder for builder in builders if builder.get("Current")}
            if len(selected) != 1:
                return
            builder = next(iter(selected.values()))
            if builder["Driver"] != "docker" or len(builder["Nodes"]) != 1 or builder["Nodes"][0]["Endpoint"] != info["ClientInfo"]["Context"]:
                return
            if os.environ.get("BUILDX_BUILDER", builder["Name"]) != builder["Name"]:
                return
            help_text = subprocess.run(["docker", "builder", "prune", "--help"], check=True,
                                       capture_output=True, text=True, timeout=15).stdout
            if "--min-free-space" not in help_text:
                return
            command = ["docker", "builder", "prune", "--force", "--filter", f"until={age}s",
                       "--min-free-space", str(self.high)]
            if self.args.apply:
                subprocess.run(command, check=True, timeout=300)
            else:
                log("would request native Docker build-cache LRU collection up to the free-space target")
        except (OSError, ValueError, KeyError, TypeError, subprocess.SubprocessError) as error:
            log(f"Docker build cache unavailable: {error}")

    def run(self):
        initial = self.free()
        log(f"available {human(initial)}; start below {human(self.low)}; stop at {human(self.high)}")
        if initial >= self.low:
            log("healthy; no discovery or cleanup needed")
            self.clear_retry()
            return 0
        if not self.retry_ready():
            return 0
        if not self.args.apply:
            self.virtual_free = initial
            log("dry run: available after removals is a conservative estimate, excluding hard-linked files")
        stages = [
            ("disposable caches idle >=7d", WEEK, lambda: self.cache_candidates() + self.tool_candidates(), True),
            ("Rust incremental sessions idle >=7d", WEEK, lambda: self.build_candidates(True), False),
        ]
        for label, age in AGES[1:]:
            stages.append((f"disposable/tool/compiler caches idle >={label}", age,
                           lambda: self.cache_candidates() + self.tool_candidates() + self.build_candidates(True), True))
        for label, age in AGES:
            stages.append((f"inactive build units idle >={label}", age, lambda: self.build_candidates(False), False))
        for number, (name, age, candidates, native_cache) in enumerate(stages, 1):
            if self.space() >= self.high:
                break
            log(f"stage {number}: {name}, LRU order")
            self.consume(candidates(), age)
            if native_cache and self.space() < self.high:
                self.docker_cache(age)
        final = self.space()
        log(f"{'projected' if not self.args.apply else 'measured'} available {human(final)}; {self.count} removal(s)")
        if final < self.high:
            log("target unmet; protected data retained")
            return 1
        self.clear_retry()
        log("target reached; stopping")
        return 0


def remove_preserving_locks(path, keep):
    if path in keep:
        return
    if not path.is_dir() or path.is_symlink():
        path.unlink()
        return
    if not any(below(lock, path) for lock in keep):
        shutil.rmtree(path)
        return
    fd = os.open(path, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_NOATIME)
    try:
        with os.scandir(fd) as entries:
            children = [path / entry.name for entry in entries]
        for child in children:
            remove_preserving_locks(child, keep)
    finally:
        os.close(fd)


def watermark(value, capacity):
    if value.endswith("%"):
        percentage = float(value[:-1])
        if not 0 < percentage < 100:
            raise ValueError("percentage watermarks must be between 0 and 100")
        return int(capacity * percentage / 100)
    match = re.fullmatch(r"([0-9]+(?:\.[0-9]+)?)(GiB|MiB)", value)
    if not match:
        raise ValueError("watermarks require % or GiB/MiB units")
    return int(float(match[1]) * (GIB if match[2] == "GiB" else 1024 ** 2))


@contextmanager
def run_lock():
    root = Path(os.environ.get("XDG_RUNTIME_DIR", os.environ.get("XDG_STATE_HOME", Path.home() / ".local/state")))
    root.mkdir(parents=True, exist_ok=True)
    fd = os.open(root / "cache-clean.lock", os.O_RDWR | os.O_CREAT | os.O_NOFOLLOW, 0o600)
    try:
        try:
            fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            yield False
        else:
            yield True
    finally:
        os.close(fd)


def metadata(arguments):
    try:
        if arguments[0] == "cmake":
            source = cmake_source(Path(arguments[1]))
            if source is None:
                return 1
            print(source)
        else:
            try:
                result, size = incremental(Path(arguments[1]), Path(arguments[2]), int(arguments[3]), arguments[4] == "true")
            except BlockingIOError:
                result, size = "preserve-locked", 0
            print(result, size)
        return 0
    except (OSError, ValueError, KeyError, TypeError):
        return 1


def main():
    if sys.argv[1:2] == ["metadata"]:
        return metadata(sys.argv[2:])
    parser = argparse.ArgumentParser(prog="cache-clean --pressure",
        description="Pressure-driven cleanup, oldest file access/modification first within each cost stage.",
        epilog="Cleanup progresses through caches and incremental sessions before inactive builds. "
               "Age steps are 7d, 3d, 1d, 6h, 1h, with LRU order and a free-space check after every unit. "
               "Units include cache files, Maven versions, Cargo packages/archives, Rust sessions and build profiles. "
               "Other build formats retain their validated whole-tree unit. File times give approximate LRU. "
               "Tracked files, runtime installations, active projects, and .cache-clean-keep markers "
               "remain protected at every stage. Enable cache-clean.timer for checks every 5 minutes; "
               "configure watermarks in ~/.config/cache-clean.conf.")
    parser.add_argument("--apply", action="store_true", help="perform cleanup (default: dry run)")
    parser.add_argument("--retry-after", type=int, default=0, metavar="SECONDS",
                        help="minimum time between unsuccessful apply attempts, including interrupted runs (default: 0)")
    parser.add_argument("--filesystem", default=str(Path.home()), help="filesystem to monitor; other devices are untouched")
    parser.add_argument("--low-watermark", default=os.environ.get("CACHE_CLEAN_LOW_WATERMARK", "5%"),
                        help="start below this available space, in %% or GiB/MiB (default: %(default)s)")
    parser.add_argument("--high-watermark", default=os.environ.get("CACHE_CLEAN_HIGH_WATERMARK", "8%"),
                        help="stop at this available space (default: %(default)s)")
    parser.add_argument("--build-root", action="append", default=[])
    parser.add_argument("--protect", action="append", default=[])
    parser.add_argument("--no-docker", action="store_true")
    if sys.argv[1:2] != ["pressure"]:
        parser.error("expected pressure or metadata subcommand")
    args = parser.parse_args(sys.argv[2:])
    if args.retry_after < 0:
        parser.error("--retry-after must be nonnegative")
    try:
        with run_lock() as acquired:
            if not acquired:
                log("another cache-clean run is active; skipping")
                return 0
            return Cleaner(args).run()
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        log(str(error))
        return 2


if __name__ == "__main__":
    sys.exit(main())
